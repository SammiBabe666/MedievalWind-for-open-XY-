"""Writes presets/<name>.json from definition.json's presets, and presets/MANIFEST.md.
Run from the repository root:
    python generators/presets.py .
Court Shawm becomes default.json, the machine's init preset. Reverberant presets
get longer amp releases: Hall and Echo ring inside the voice, so a tail lasts as
long as the stock amp envelope lets the voice sound."""
import json, sys, copy, os
root = sys.argv[1] if len(sys.argv) > 1 else '.'
# A version 4 OP-XY preset, as the device saves one; engine params and the amp envelope are filled in below.
TEMPLATE = json.loads('{"engine": {"bendrange": 8191, "highpass": 0, "modulation": {"aftertouch": {"amount": 16384, "target": 0}, "modwheel": {"amount": 16384, "target": 0}, "pitchbend": {"amount": 16384, "target": 0}, "velocity": {"amount": 16384, "target": 0}}, "params": [0, 0, 0, 0, 0, 0, 0, 0], "playmode": "poly", "portamento.amount": 0, "portamento.type": 0, "transpose": 0, "tuning.root": 0, "tuning.scale": 0, "velocity.sensitivity": 0, "volume": 16384, "width": 0}, "envelope": {"amp": {"attack": 0, "decay": 8192, "release": 6000, "sustain": 32767}, "filter": {"attack": 0, "decay": 0, "release": 0, "sustain": 32767}}, "fx": {"active": false, "params": [0, 0, 0, 0, 0, 32767, 0, 0], "type": "svf"}, "lfo": {"active": false, "params": [0, 0, 0, 0, 0, 0, 0, 0], "type": "value"}, "octave": 0, "platform": "OP-XY", "regions": [], "type": "medievalwind", "version": 4}')
# File name, amp attack and release (stock 0..32767), and the intended character.
PRESETS = {
    'Court Shawm': ('default', 300, 5000, "Bright, direct, unmistakably reedy: the default"),
    'Blackwood': ('blackwood', 600, 6000, "A darker, woody shawm with restrained upper harmonics"),
    'Hollow Procession': ('hollow-procession', 300, 8000, "Powerful, projecting ceremonial tone"),
    'Chapel Reed': ('chapel-reed', 900, 14000, "Sustained medieval melody in a spacious hall"),
    'The Crumhorn': ('the-crumhorn', 200, 4000, "Nasal, pinched, dark and buzzing: odd harmonics only"),
    'The Kings Fool': ('the-kings-fool', 150, 5000, "Characterful, cutting, slightly unstable reed"),
    'Moth in the Belfry': ('moth-in-the-belfry', 2200, 16000, "Breathy, fragile, haunting and atmospheric"),
    'The Black Court': ('the-black-court', 700, 12000, "Dark, dense and harmonically rich"),
    'Pilgrims Drone': ('pilgrims-drone', 2600, 14000, "A restrained, sustained, hollow medieval tone"),
    'Last Light Through Stone': ('last-light-through-stone', 1600, 18000, "Expressive, breathy and reverberant"),
}
DISPLAY = {'The Kings Fool': 'The King’s Fool', 'Pilgrims Drone': 'Pilgrim’s Drone'}
d = json.load(open(os.path.join(root, 'definition.json')))
ids = [p['id'] for p in d['parameters']]
assert list(d['presets']) == list(PRESETS), 'definition.json and generators/presets.py list different presets'
os.makedirs(os.path.join(root, 'presets'), exist_ok=True)
rows = []
for name, values in d['presets'].items():
    file, attack, release, character = PRESETS[name]
    p = copy.deepcopy(TEMPLATE)
    p['type'] = d['id']
    p['engine']['params'] = [round(values[i] * 32767) for i in ids] + [0] * (8 - len(ids))
    p['envelope']['amp'] = {'attack': attack, 'decay': 8192, 'release': release, 'sustain': 32767}
    with open(os.path.join(root, 'presets', file + '.json'), 'w') as f:
        json.dump(p, f, indent=2, sort_keys=True)
        f.write('\n')
    rows.append('| %s | `%s.json` | %s | %d | %d | %s |' % (DISPLAY.get(name, name), file,
                ' | '.join('%g' % round(values[i] * 100, 1) for i in ids), attack, release, character))
manifest = ['# Factory presets', '',
            'Generated by `generators/presets.py` from `definition.json`; do not edit by hand.',
            'Controls are shown 0 to 100 (the header\'s amounts); amp attack and release are the stock 0..32767 values.', '',
            '| Preset | File | ' + ' | '.join(p['label'] for p in d['parameters']) + ' | Attack | Release | Character |',
            '| --- | --- | ' + ' | '.join('---' for _ in ids) + ' | --- | --- | --- |'] + rows
open(os.path.join(root, 'presets', 'MANIFEST.md'), 'w').write('\n'.join(manifest) + '\n')
print(len(rows), 'presets')
